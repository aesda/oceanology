export function buildNepaliSunDegreeSymbol(signIndex: number, degreeInSign: number): string {
  const safeSign = ((signIndex % 12) + 12) % 12;
  const signNe = trSign(ZODIAC_SIGNS[safeSign].name, 'ne');
  const deg = Math.max(1, Math.min(30, Math.ceil(degreeInSign)));
  return `${signNe} ${toNepaliDigits(deg)}°: ${SUN_SIGN_THEMES_NE[safeSign]}`;
}
