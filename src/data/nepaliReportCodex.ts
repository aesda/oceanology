export function buildNepaliPadaExpression(
  nakIndex: number,
  pada: number,
  navamshaSignEn: string,
  navamshaRulerEn: string,
  specialTag?: string
): string {
  const nakNe = getNepaliNakshatraEntry(nakIndex).nameNe;
  const signClean = navamshaSignEn.includes('(')
    ? navamshaSignEn.split('(')[1].replace(')', '').trim()
    : navamshaSignEn;
  const navSignNe = trSign(signClean, 'ne');
  const navRulerNe = trPlanet(navamshaRulerEn, 'ne');
  const flavor =
    NAVAMSHA_RULER_FLAVOR_NE[navamshaRulerEn] || 'सन्तुलित विवेक र व्यावहारिक स्थिरता';

  const tagSentence =
    specialTag === 'Vargottama'
      ? ' यो वर्गोत्तम चरण भएकाले उमेर बढ्दै जाँदा तपाईंको आन्तरिक आत्मविश्वास र फल अझ सुदृढ हुन्छ।'
      : specialTag === 'Pushkara Navamsha'
      ? ' यो शुभ पुष्कर नवांशमा परेकाले कठिन समयमा पनि पोषण, अवसर र पुनःउत्थानको विशेष आशीर्वाद मिल्छ।'
      : specialTag === 'Vargottama & Pushkara'
      ? ' यो दुर्लभ वर्गोत्तम तथा पुष्कर नवांश संगम भएकाले जीवनमा असाधारण आन्तरिक बल र शुभ फल प्राप्त हुन्छ।'
      : specialTag === 'Gandanta' || specialTag === 'Abhukta Mula'
      ? ' सन्धि अंशको संवेदनशीलता रहेकाले महत्त्वपूर्ण निर्णयमा धैर्य र ध्यान अभ्यासले ठूलो आध्यात्मिक प्रज्ञा खोल्छ।'
      : '';

  return `${nakNe} नक्षत्रको चरण ${toNepaliDigits(pada)} ले ${navSignNe} नवांश (${navRulerNe} शासित) को प्रभाव बोक्छ—जसले तपाईंको स्वभावमा ${flavor} जोड्दछ।${tagSentence}`;
}

