export function getAuthenticSabianSymbol(
  tropicalLon: number,
  signNames: { name: string }[] = DEFAULT_SIGN_NAMES
): string {
  const norm = ((tropicalLon % 360) + 360) % 360;
  const degIndex = Math.min(359, Math.floor(norm));
  const signIdx = Math.floor(degIndex / 30);
  const degInSign = (degIndex % 30) + 1;
  const symbolPhrase = SABIAN_360_SYMBOLS[degIndex];
  return `${signNames[signIdx].name} ${degInSign}°: "${symbolPhrase}."`;
}
