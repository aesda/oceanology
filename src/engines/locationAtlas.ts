export interface BikramSambatDate {
  bsYear: number;
  bsMonthIndex: number; // 1-12
  bsMonthEn: string;
  bsMonthNp: string;
  bsDay: number;
  formattedEn: string;
  formattedNp: string;
}

export function gregorianToBikramSambat(year: number, month: number, day: number): BikramSambatDate {
  // Baisakh 1 starts around April 13/14 (+56 years, 8 months, 17 days offset from Gregorian)
  const targetUtc = Date.UTC(year, month - 1, day);
  const baisakhStartThisYear = Date.UTC(year, 3, 14); // April 14
  let bsYear = targetUtc >= baisakhStartThisYear ? year + 57 : year + 56;
  const refBaisakh = targetUtc >= baisakhStartThisYear
    ? baisakhStartThisYear
    : Date.UTC(year - 1, 3, 14);

  let daysElapsed = Math.floor((targetUtc - refBaisakh) / 86400000);
  if (daysElapsed < 0) daysElapsed = 0;

  // Typical Bikram Sambat month lengths (total 365/366)
  const monthLengths = [31, 31, 32, 32, 31, 30, 30, 29, 30, 29, 30, 30];
  let mIdx = 0;
  while (mIdx < 11 && daysElapsed >= monthLengths[mIdx]) {
    daysElapsed -= monthLengths[mIdx];
    mIdx++;
  }
  const bsDay = daysElapsed + 1;
  const mObj = NEPALI_MONTHS[mIdx];

  return {
    bsYear,
    bsMonthIndex: mObj.index,
    bsMonthEn: mObj.en,
    bsMonthNp: mObj.np,
    bsDay,
    formattedEn: `${bsYear} ${mObj.en} ${bsDay} B.S.`,
    formattedNp: `${bsYear} ${mObj.np} ${bsDay} गते`,
  };
}


/**
 * Strips parenthetical native script (e.g. "Kathmandu (काठमाडौँ)" -> "Kathmandu")
 * while preserving multi-word English city names like "New York" or "New Delhi".
 */
export function cleanCityName(rawName: string): string {
  return rawName.replace(/\s*\([^)]*\)\s*/g, '').trim();
}

export function resolveTimezoneOffsetAtDate(
  location: CityLocation,
  atDate: Date = new Date()
): number {
  if (
    location.id !== 'custom-loc' &&
    location.ianaTimezone &&
    location.ianaTimezone !== 'UTC'
  ) {
    try {
      const tzString = atDate.toLocaleString('en-US', {
        timeZone: location.ianaTimezone,
        timeZoneName: 'shortOffset',
      });
      const match = tzString.match(/GMT([+-]\d+)(?::(\d+))?/);
      if (match) {
        const sign = match[1].startsWith('-') ? -1 : 1;
        const hrs = Math.abs(parseInt(match[1], 10));
        const mins = match[2] ? parseInt(match[2], 10) / 60 : 0;
        return sign * (hrs + mins);
      }
    } catch {
      // Fallback to stored static offset
    }
  }
  return location.timezoneOffsetHours;
}

export function formatCoordPair(lat: number, lon: number, asciiOnly = false): string {
  const ns = lat >= 0 ? 'N' : 'S';
  const ew = lon >= 0 ? 'E' : 'W';
  const deg = asciiOnly ? '' : '°';
  return `${Math.abs(lat).toFixed(2)}${deg}${ns}, ${Math.abs(lon).toFixed(2)}${deg}${ew}`;
}

