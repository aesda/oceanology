// Estimate standard UTC offset from IANA timezone string or longitude
export function getOffsetFromIanaOrLon(iana: string | undefined, lon: number): number {
  if (iana) {
    try {
      const now = new Date();
      const tzString = now.toLocaleString('en-US', { timeZone: iana, timeZoneName: 'shortOffset' });
      const match = tzString.match(/GMT([+-]\d+)(?::(\d+))?/);
      if (match) {
        const sign = match[1].startsWith('-') ? -1 : 1;
        const hrs = Math.abs(parseInt(match[1], 10));
        const mins = match[2] ? parseInt(match[2], 10) / 60 : 0;
        return sign * (hrs + mins);
      }
    } catch {
      // Fallback to longitude approximation
    }
  }
  return Math.round((lon / 15) * 4) / 4;
}

// Live Global Geocoding API (Open-Meteo Geocoding — finds any city/village in Nepal or worldwide with elevation!)
export async function searchGlobalLocations(query: string): Promise<CityLocation[]> {
  const q = query.trim();
  if (q.length < 2) return [];

  const localMatches = NEPAL_AND_GLOBAL_CITIES.filter(
    c =>
      c.name.toLowerCase().includes(q.toLowerCase()) ||
      c.country.toLowerCase().includes(q.toLowerCase()) ||
      c.state.toLowerCase().includes(q.toLowerCase())
  );

  try {
    const res = await fetch(
      `https://geocoding-api.open-meteo.com/v1/search?name=${encodeURIComponent(q)}&count=8&language=en&format=json`
    );
    if (!res.ok) return localMatches;
    const data = await res.json();
    if (!data.results || !Array.isArray(data.results)) return localMatches;

    const remoteCities: CityLocation[] = data.results.map((r: any) => {
      const iana = r.timezone || 'UTC';
      const offset = getOffsetFromIanaOrLon(iana, r.longitude);
      return {
        id: `geo-${r.id || `${r.latitude}-${r.longitude}`}`,
        name: r.name,
        state: r.admin1 || r.country || '',
        country: r.country || '',
        latitude: Number(r.latitude) || 0,
        longitude: Number(r.longitude) || 0,
        elevationMeters: Math.round(Number(r.elevation) || 0),
        timezoneOffsetHours: offset,
        ianaTimezone: iana,
      };
    });

    const seen = new Set(localMatches.map(c => `${c.name.split(' ')[0].toLowerCase()}-${c.country.toLowerCase()}`));
    const merged = [...localMatches];
    for (const rc of remoteCities) {
      const key = `${rc.name.toLowerCase()}-${rc.country.toLowerCase()}`;
      if (!seen.has(key)) {
        seen.add(key);
        merged.push(rc);
      }
    }
    return merged.slice(0, 12);
  } catch {
    return localMatches;
  }
}

